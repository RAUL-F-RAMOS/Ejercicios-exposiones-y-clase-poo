package Operaciones;
import Operaciones.*;
public class Operaciones_aritmeticas {
    int n1,n2;

    public Operaciones_aritmeticas(int n1,int n2){
        this.n1=n1;
        this.n2=n2;
    }
    public void suma(int n1,int n2){
        System.out.println("suma: "+(n1+n2));
    }

    public void resta(int n1,int n2){
        System.out.println("resta: "+(n1-n2));
    }
    public void mutliplicacion(int n1,int n2){
        System.out.println("multiplicacion: "+(n1*n2));
    }
    public void division(int n1,int n2){
        System.out.println("division: "+(n1/n2));
    }
    public void potencia(int n1,int n2){
        System.out.println("multiplicacion: "+(n1*n2));
    }
}
